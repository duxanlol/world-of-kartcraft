#!/usr/bin/env python3
"""The Marathon Delivery's schedule: sql/kartcraft_marathons.sql, for the world database (mangos).

Every MARATHON_HOURS of a weekend, Vienna time (Saturday and Sunday, daylight saving followed),
for the next WEEKENDS weekends from today, the continents taking turns. Run it to extend the
schedule, then deploy: the deploy applies every sql/*.sql. A start already in the table keeps
its row (INSERT IGNORE), so a marathon run (`done`) stays run.

    python3 setup/vmangos/marathons.py
"""

import datetime
import os
import zoneinfo

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'sql', 'kartcraft_marathons.sql')

ZONE = zoneinfo.ZoneInfo('Europe/Vienna')
MARATHON_HOURS = (0, 8, 16)
WEEKEND_DAYS = (5, 6)  # Saturday, Sunday (Monday is 0)
WEEKENDS = 12
MAPS = (0, 1)  # the Eastern Kingdoms, Kalimdor


def starts(today):
    out = []
    day = today
    while len(out) < WEEKENDS * len(WEEKEND_DAYS) * len(MARATHON_HOURS):
        if day.weekday() in WEEKEND_DAYS:
            for hour in MARATHON_HOURS:
                local = datetime.datetime(day.year, day.month, day.day, hour, tzinfo=ZONE)
                out.append(int(local.timestamp()))
        day += datetime.timedelta(days=1)
    return out


def main():
    today = datetime.datetime.now(ZONE).date()
    rows = []
    for i, t in enumerate(starts(today)):
        when = datetime.datetime.fromtimestamp(t, ZONE).strftime('%a %Y-%m-%d %H:%M %Z')
        rows.append(f'({t}, {MAPS[i % len(MAPS)]}, 0), -- {when}')
    rows[-1] = rows[-1].replace('), --', '); --', 1)
    text = '\n'.join([
        '-- Generated by setup/vmangos/marathons.py: rerun it to extend the schedule. The Marathon',
        '-- Delivery\'s starts (unix time, UTC), the continent (0 the Eastern Kingdoms, 1 Kalimdor),',
        '-- and whether it has run; Kartcraft.cpp opens each one\'s queue ten minutes before it.',
        'CREATE TABLE IF NOT EXISTS `kartcraft_marathons` (',
        "  `starts` INT UNSIGNED NOT NULL COMMENT 'unix time, UTC',",
        "  `map` TINYINT UNSIGNED NOT NULL COMMENT '0 the Eastern Kingdoms, 1 Kalimdor',",
        "  `done` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '1 once run, or missed',",
        '  PRIMARY KEY (`starts`)',
        ') ENGINE=InnoDB DEFAULT CHARSET=utf8;',
        '',
        'INSERT IGNORE INTO `kartcraft_marathons` (`starts`, `map`, `done`) VALUES',
        *rows,
        '',
    ])
    with open(OUT, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)
    print(f'{len(rows)} marathons written to {OUT}')


if __name__ == '__main__':
    main()
